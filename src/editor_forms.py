class InputSheets:
    """Layout helpers; the host supplies fields, document and atomic flushing."""

    def _value(self, path: JsonPath, default: Any = None) -> Any:
        try:
            return get_at(self.document.data, path)
        except (KeyError, IndexError, TypeError):
            return default

    def _unit(self, path: JsonPath) -> str:
        if path == ("下部構造", "斜角", "タイプ"):
            return ""
        try:
            return unit_label(self.document.data, path).replace("m3", "m³").replace("m2", "m²")
        except (KeyError, IndexError, TypeError):
            return ""

    def _declared_unit(self, section: str, key: str) -> str:
        value = self._value((section, "単位", key))
        return value.replace("m3", "m³").replace("m2", "m²") if isinstance(value, str) else "単位未記載"

    def _section(self, parent: ttk.Frame, title: str, *, note: str = "") -> ttk.Frame:
        frame = ttk.LabelFrame(parent, text=title, padding=12, style="Sheet.TLabelframe")
        frame.pack(fill="x", pady=(0, 14))
        if note:
            ttk.Label(frame, text=note, style="Muted.TLabel", wraplength=980).pack(anchor="w", pady=(0, 9))
        body = ttk.Frame(frame)
        body.pack(fill="x")
        return body

    def _properties(self, parent: ttk.Frame, specs: list, *, choices: dict | None = None,
                    widths: list[int] | None = None, max_height: int = 350) -> None:
        self._grid(parent, ["項目・記号", "値", "単位"],
                   [[label, path, self._unit(path)] for path, label in specs],
                   widths or [240, 150, 125], choices=choices, max_height=max_height)

    def _figure(self, parent: ttk.Frame, name: str, caption: str) -> None:
        frame = ttk.Frame(parent, padding=(10, 0, 0, 0))
        frame.pack(fill="x")
        path = Path(__file__).with_name("assets") / f"{name}.png"
        try:
            photo = self._images.get(name)
            if photo is None:
                photo = tk.PhotoImage(master=self.root, file=str(path))
                self._images[name] = photo
            label = ttk.Label(frame, image=photo, cursor="hand2", background="white")
            label.pack(anchor="center")
            label.bind("<Button-1>", lambda event: self._enlarge_figure(name, caption))
            ttk.Label(frame, text=caption + "  ·  クリックで拡大", style="Caption.TLabel", wraplength=600).pack(anchor="center", pady=(6, 0))
        except tk.TclError:
            ttk.Label(frame, text="参照図を読み込めませんでした。", style="Muted.TLabel", wraplength=450).pack()

    def _enlarge_figure(self, name: str, caption: str) -> None:
        window = tk.Toplevel(self.root)
        window.title(caption + " — 原図・記号確認用")
        window.geometry("1100x760")
        ttk.Label(window, text="原図・記号確認用（入力値には連動しません）", padding=10).pack(anchor="w")
        body = ttk.Frame(window)
        body.pack(fill="both", expand=True)
        canvas = tk.Canvas(body, background="white", highlightthickness=0)
        vertical = ttk.Scrollbar(body, orient="vertical", command=canvas.yview)
        horizontal = ttk.Scrollbar(body, orient="horizontal", command=canvas.xview)
        canvas.configure(yscrollcommand=vertical.set, xscrollcommand=horizontal.set)
        canvas.grid(row=0, column=0, sticky="nsew")
        vertical.grid(row=0, column=1, sticky="ns")
        horizontal.grid(row=1, column=0, sticky="ew")
        body.rowconfigure(0, weight=1)
        body.columnconfigure(0, weight=1)
        large = Path(__file__).with_name("assets") / f"{name}_large.png"
        try:
            photo = tk.PhotoImage(master=window, file=str(large)) if large.exists() else self._images[name]
        except tk.TclError:
            photo = self._images[name]
        window._reference_image = photo  # Keep the Tcl image alive with its window.
        canvas.create_image(12, 12, image=photo, anchor="nw")
        canvas.configure(scrollregion=canvas.bbox("all"))
        window.bind("<Escape>", lambda event: window.destroy())

